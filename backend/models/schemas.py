from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from datetime import datetime
from backend.models.enums import (
    PipelineStage,
    StageStatus,
    VisualType,
    AssetStatus,
    VoiceGender,
    VideoDuration,
    VideoStyle,
)

# -------------------------------------------------------------
# Input & Configuration Models
# -------------------------------------------------------------
class VideoCreateRequest(BaseModel):
    niche: str = Field(..., example="AI & Technology")
    topic: str = Field(..., example="5 AI Agents Every Developer Should Know")
    target_audience: str = Field(..., example="University students and beginner developers")
    language: str = Field(default="English", example="English")
    duration: VideoDuration = Field(default=VideoDuration.DUR_5)
    style: VideoStyle = Field(default=VideoStyle.EDUCATIONAL)
    voice: VoiceGender = Field(default=VoiceGender.NEUTRAL)
    reference_channel: Optional[str] = Field(default="", example="@TwoMinutePapers")
    brand_info: Optional[str] = Field(default="", example="Modern dark tech theme, high energy")

# -------------------------------------------------------------
# Stage Specific Models
# -------------------------------------------------------------
class ContentAngle(BaseModel):
    id: str
    title: str
    description: str
    target_viewer: str
    hook_premise: str
    estimated_retention: str

class ContentStrategy(BaseModel):
    topic: str
    niche: str
    audience: str
    angles: List[ContentAngle] = []
    selected_angle: ContentAngle
    core_promise: str
    unique_selling_point: str
    suggested_video_structure: List[str] = []
    viewer_intent: str
    educational_value: str

class TitleOption(BaseModel):
    id: str
    title: str
    clarity_score: int  # 1-10
    curiosity_score: int  # 1-10
    relevance_score: int  # 1-10
    search_intent_score: int  # 1-10
    click_potential_score: int  # 1-10
    length_chars: int
    rationale: str

class HookData(BaseModel):
    hook_text: str
    hook_duration_sec: int
    visual_direction: str
    problem_statement: str
    value_promise: str

class ScriptScene(BaseModel):
    scene_number: int
    section: str  # HOOK, INTRO, PROBLEM, MAIN_CONTENT, EXAMPLES, KEY_TAKEAWAYS, CTA
    duration_sec: int
    narration: str
    visual_direction: str
    on_screen_text: str
    transition: str

class FullScript(BaseModel):
    selected_title: str
    hook: str
    target_duration_sec: int
    estimated_word_count: int
    scenes: List[ScriptScene] = []
    full_narration: str
    call_to_action: str

class StoryboardScene(BaseModel):
    scene_id: str
    scene_number: int
    duration_sec: int
    narration: str
    visual_description: str
    suggested_visual_type: VisualType
    image_prompt: str
    video_prompt: str
    on_screen_text: str
    transition: str
    music_mood: str
    asset_status: AssetStatus = AssetStatus.PLACEHOLDER
    image_url: Optional[str] = None
    video_url: Optional[str] = None
    audio_url: Optional[str] = None
    provider_name: str = "Local Engine"

class ThumbnailConcept(BaseModel):
    id: str
    title_text: str
    visual_concept: str
    composition: str
    subject: str
    color_direction: str
    emotion: str
    image_prompt: str
    clarity_score: int
    curiosity_score: int
    relevance_score: int
    mobile_readability_score: int
    visual_hierarchy_score: int
    overall_score: float
    is_selected: bool = False
    image_url: Optional[str] = None

class SEOPackage(BaseModel):
    title: str
    description: str
    short_description: str
    chapters: List[Dict[str, str]] = []  # [{"time": "00:00", "title": "Intro"}]
    keywords: List[str] = []
    tags: List[str] = []
    hashtags: List[str] = []
    pinned_comment: str

class QualityCheckItem(BaseModel):
    category: str  # Content, Production, Package
    name: str
    passed: bool
    details: str
    severity: str = "warning"  # info, warning, error

class QualityCheckReport(BaseModel):
    passed: bool
    checked_at: str
    checks: List[QualityCheckItem] = []
    issues_identified: List[str] = []
    retry_required: bool = False
    affected_stage: Optional[str] = None
    recommendations: List[str] = []

class FinalPackage(BaseModel):
    video_id: str
    title: str
    description: str
    thumbnail_url: str
    video_url: str
    duration_sec: int
    resolution: str = "1920x1080"
    file_size_mb: float = 0.0
    seo: SEOPackage
    created_at: str
    is_ready_for_review: bool = True
    disclaimer: str = "Generated by CreatorFlow AI. Please review and verify content before uploading to YouTube."

class ActivityLogEntry(BaseModel):
    timestamp: str
    stage: str
    action: str
    details: Optional[str] = None
    status: str = "info"  # info, success, warning, error

# -------------------------------------------------------------
# Master CreatorState
# -------------------------------------------------------------
class CreatorState(BaseModel):
    # Core project specifications
    project_id: str
    created_at: str
    updated_at: str
    niche: str
    topic: str
    target_audience: str
    language: str
    duration: VideoDuration
    style: VideoStyle
    voice: VoiceGender
    reference_channel: Optional[str] = ""
    brand_info: Optional[str] = ""

    # Pipeline state tracking
    current_stage: PipelineStage = PipelineStage.IDLE
    stage_statuses: Dict[str, StageStatus] = {}

    # Generated Stage Artifacts
    content_strategy: Optional[ContentStrategy] = None
    selected_angle: Optional[ContentAngle] = None
    title_options: List[TitleOption] = []
    selected_title: Optional[str] = None
    hook: Optional[HookData] = None
    script: Optional[FullScript] = None

    storyboard: List[StoryboardScene] = []
    thumbnail_concepts: List[ThumbnailConcept] = []
    selected_thumbnail: Optional[ThumbnailConcept] = None
    seo: Optional[SEOPackage] = None

    # Quality control
    quality_checks: Optional[QualityCheckReport] = None
    validation_retry_count: int = 0

    # Final assets & packaging
    rendered_video_url: Optional[str] = None
    final_package: Optional[FinalPackage] = None

    # Human-in-the-loop approvals
    script_approved: bool = False
    production_approved: bool = False
    waiting_for_approval_type: Optional[str] = None  # "script" or "production"

    # Activity Logging (safe, high-level action events)
    activity_logs: List[ActivityLogEntry] = []

    # Error handling
    error_message: Optional[str] = None

class HumanApprovalRequest(BaseModel):
    approval_type: str  # "script" or "production"
    decision: str  # "approve", "regenerate", "edit"
    edits: Optional[Dict[str, Any]] = None

class DashboardMetrics(BaseModel):
    videos_created: int
    in_production: int
    completed: int
    assets_generated: int
